#!/usr/bin/env python3
import os
import re
import shutil
import subprocess
from datetime import datetime, timezone
from pathlib import Path


CADDY_FILE = Path(os.environ.get("CADDY_FILE", "/opt/caddy/Caddyfile"))
HASH_FILE = Path(os.environ.get("BASIC_AUTH_HASH_FILE", "/opt/caddy/arcfolio-basic-auth.hash"))
USERNAME = os.environ.get("BASIC_AUTH_USER", "arcfolio-preview")
PRODUCTION_HOST = os.environ.get("PRODUCTION_HOST", "arcfolio.ryzko.pl")
DEVELOPMENT_HOST = os.environ.get("DEVELOPMENT_HOST", "dev.arcfolio.ryzko.pl")
PRODUCTION_UPSTREAM = os.environ.get("PRODUCTION_UPSTREAM", "arcfolio-web:80")
DEVELOPMENT_UPSTREAM = os.environ.get("DEVELOPMENT_UPSTREAM", "arcfolio-dev-web:80")
START_MARKER = "# BEGIN ARCFOLIO MANAGED"
END_MARKER = "# END ARCFOLIO MANAGED"


def validate_token(label: str, value: str) -> str:
    if not re.fullmatch(r"[A-Za-z0-9._:@-]+", value):
        raise ValueError(f"Invalid {label}")
    return value


def site_block(host: str, upstream: str, password_hash: str) -> str:
    return f"""{host} {{
    header X-Robots-Tag \"noindex, nofollow, noarchive\"
    basic_auth {{
        {USERNAME} {password_hash}
    }}
    reverse_proxy {upstream}
}}"""


for label, value in (
    ("username", USERNAME),
    ("production host", PRODUCTION_HOST),
    ("development host", DEVELOPMENT_HOST),
    ("production upstream", PRODUCTION_UPSTREAM),
    ("development upstream", DEVELOPMENT_UPSTREAM),
):
    validate_token(label, value)

password_hash = HASH_FILE.read_text(encoding="utf-8").strip()
if not password_hash.startswith("$2"):
    raise ValueError("Expected a bcrypt hash generated by Caddy")

original = CADDY_FILE.read_text(encoding="utf-8")
without_managed = re.sub(
    rf"\n?{re.escape(START_MARKER)}.*?{re.escape(END_MARKER)}\n?",
    "\n",
    original,
    flags=re.DOTALL,
)
without_legacy = re.sub(
    rf"\n?^{re.escape(PRODUCTION_HOST)} \{{\n\s*reverse_proxy\s+{re.escape(PRODUCTION_UPSTREAM)}\n\}}\n?",
    "\n",
    without_managed,
    flags=re.MULTILINE,
)

managed = "\n\n".join(
    (
        START_MARKER,
        site_block(PRODUCTION_HOST, PRODUCTION_UPSTREAM, password_hash),
        site_block(DEVELOPMENT_HOST, DEVELOPMENT_UPSTREAM, password_hash),
        END_MARKER,
    )
)
updated = without_legacy.rstrip() + "\n\n" + managed + "\n"

timestamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
backup = CADDY_FILE.with_name(f"Caddyfile.before-arcfolio-{timestamp}")
shutil.copy2(CADDY_FILE, backup)
CADDY_FILE.write_text(updated, encoding="utf-8")

try:
    subprocess.run(
        ["docker", "exec", "caddy", "caddy", "validate", "--config", "/etc/caddy/Caddyfile"],
        check=True,
    )
    subprocess.run(
        ["docker", "exec", "caddy", "caddy", "reload", "--config", "/etc/caddy/Caddyfile"],
        check=True,
    )
except subprocess.CalledProcessError:
    shutil.copy2(backup, CADDY_FILE)
    raise

print(f"Caddy updated. Backup: {backup}")
